import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import '../src/shared/finance-core.js';
import {createFinanceInsights} from '../src/shared/finance-insights.js';
const F=globalThis.FinanceCore;
const nodes=new Map(),node=id=>{if(!nodes.has(id))nodes.set(id,{value:'',innerHTML:''});return nodes.get(id);};
let opened;
const context=vm.createContext({FinanceCore:F,FinanceInsights:createFinanceInsights(F),db:{transactions:[]},profile:'personal',dateToday:'2026-11-02',$:node,persist(){},esc:s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c])),money:n=>Number(n).toFixed(2),modal:(title,html)=>{opened={title,html};}});
for(const file of ['finance-ui.js','finance-widgets.js'])vm.runInContext(fs.readFileSync(new URL('../src/client/'+file,import.meta.url),'utf8'),context);
node('personalMonth').value='2026-11';
F.ensureCreditCards(context.db,'2026-11');
const rent=F.createBill(context.db,{description:'Aluguel de novembro',category:'Moradia',dueDate:'2026-11-10',expectedAmount:100});
const water=F.createBill(context.db,{description:'Agua sem estimativa',category:'Agua',dueDate:'2026-11-15',expectedAmount:null});
const future=F.createBill(context.db,{description:'Conta de dezembro',category:'Moradia',dueDate:'2026-12-10',expectedAmount:200});
context.renderPersonalFinance();
let html=node('personalFinanceContent').innerHTML;
assert.ok(html.indexOf('Contas do mês')<html.indexOf('Meta acumulada da reserva'),'Bills replace the middle indicator card above reserve and monthly overview');
assert.ok(html.indexOf('Gastos por categoria')>html.indexOf('Visão de'),'The category chart moves to the former bills position');
assert.match(html,/data-bills-month="2026-11"/);assert.match(html,/Aluguel de novembro/);
F.payBill(context.db,rent.id,{amount:100,date:'2026-11-02',method:'pix'});
context.renderPersonalFinance();
assert.match(node('personalFinanceContent').innerHTML,/data-bills-month="2026-11"/,'An unknown unpaid amount keeps its month open');
F.payBill(context.db,water.id,{amount:25,date:'2026-11-02',method:'pix'});
context.renderPersonalFinance();html=node('personalFinanceContent').innerHTML;
assert.match(html,/data-bills-month="2026-12"/,'After the last payment, zero-value card placeholders must not prevent advancing');
assert.match(html,/Conta de dezembro/);assert.equal(node('personalMonth').value,'2026-11','The reference filter still lets users inspect the original month');
context.openFinanceExpenses('bills',false,'2026-12');
assert.match(opened.html,/value="2026-12"/,'The bills action must open the month actually shown in the card');
assert.match(opened.html,/Conta de dezembro/);assert.doesNotMatch(opened.html,/Aluguel de novembro/);
const beforePaid=structuredClone(context.db.finance.bills.find(b=>b.id===rent.id));
F.payBill(context.db,future.id,{amount:200,date:'2026-11-02',method:'pix'});
context.renderPersonalFinance();assert.match(node('personalFinanceContent').innerHTML,/data-bills-month="2027-01"/,'Consecutive settled months advance correctly across the year');
assert.deepEqual(context.db.finance.bills.find(b=>b.id===rent.id),beforePaid,'Auto-advance must preserve paid history');
context.db={transactions:[]};node('personalMonth').value='2026-11';
context.renderPersonalFinance();assert.match(node('personalFinanceContent').innerHTML,/data-bills-month="2026-11"/,'Empty months stay visible instead of skipping indefinitely');
assert.match(node('personalFinanceContent').innerHTML,/Nenhuma conta/);
const cancelled=F.createBill(context.db,{description:'Cancelada',category:'Outros',dueDate:'2026-11-12',expectedAmount:10});F.cancelBill(context.db,cancelled.id);
context.renderPersonalFinance();assert.match(node('personalFinanceContent').innerHTML,/data-bills-month="2026-12"/,'Cancelled obligations do not keep a completed month open');
for(const [month,next] of [['0999-11','0999-12'],['0999-12','1000-01']]){
 context.db={transactions:[]};
 const old=F.createBill(context.db,{description:'Historical bill',category:'Outros',dueDate:month+'-10',expectedAmount:5});
 F.payBill(context.db,old.id,{amount:5,date:'2026-11-02',method:'pix'});
 assert.equal(context.financeBillsOverview(month).month,next,'All valid four-digit years retain their padding during rollover');
}
console.log('Bills overview passed: swapped sections, final-payment advance, unknown values, zero placeholders, year rollover, empty months, modal month and preserved paid history.');
