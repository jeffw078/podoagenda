import assert from 'node:assert/strict';
import '../src/shared/finance-core.js';
const F=globalThis.FinanceCore;
const data={transactions:[]};
F.recordCreditPurchase(data,{cardId:'nubank',description:'Compra atual',category:'Outros',purchaseDate:'2026-10-01',amount:300,items:[],installments:[{date:'2099-01-01',amount:100,installmentNumber:1,installmentCount:3},{date:'2099-02-01',amount:100,installmentNumber:2,installmentCount:3},{date:'2099-03-01',amount:100,installmentNumber:3,installmentCount:3}]});
const purchase=data.finance.creditPurchases[0];
F.payBill(data,'recurring:card:nubank:2099-01',{amount:100,date:'2099-01-10',method:'pix'});
const before=structuredClone(data),parts=structuredClone(purchase.installments);
parts[1].amount=90;parts[2].date='2099-04-01';
assert.equal(typeof F.editCreditInstallments,'function','Future card installments can be edited');
F.editCreditInstallments(data,purchase.id,{installments:parts,reason:'Desconto e mudança de vencimento'});
assert.equal(data.finance.creditPurchases[0].amount,290);
assert.equal(data.finance.bills.find(b=>b.id==='recurring:card:nubank:2099-02').expectedAmount,90);
assert.equal(data.finance.bills.find(b=>b.id==='recurring:card:nubank:2099-03').expectedAmount,0);
assert.equal(data.finance.bills.find(b=>b.id==='recurring:card:nubank:2099-04').expectedAmount,100);
assert.deepEqual(data.finance.bills.find(b=>b.status==='paid'),before.finance.bills.find(b=>b.status==='paid'));
assert.deepEqual(data.transactions,before.transactions,'Editing future debt creates no cash movement');
assert.equal(F.validateFinanceChange(before,data),true);
assert.equal(data.finance.creditEdits.length,1);
const duplicatedDebt=structuredClone(data);duplicatedDebt.finance.bills.find(b=>b.id==='recurring:card:nubank:2099-03').expectedAmount=100;
assert.equal(F.validateFinanceChange(before,duplicatedDebt),false,'Moving a parcel cannot retain its debt in the old invoice');
assert.equal(F.validateFinanceChange(data,duplicatedDebt),false,'A later save cannot restore debt in a vacated invoice');
const snapshot=structuredClone(data);
for(const mutate of [p=>{p[0].amount=1},p=>{p[1].date='2020-01-01'},p=>{p[2].date=p[1].date}]){
 const invalid=structuredClone(data.finance.creditPurchases[0].installments);mutate(invalid);
 assert.throws(()=>F.editCreditInstallments(data,purchase.id,{installments:invalid,reason:'Teste'}));
 assert.deepEqual(data,snapshot,'Invalid edits must be atomic');
}
assert.throws(()=>F.editCreditInstallments(data,purchase.id,{installments:parts,reason:''}));
const forged=structuredClone(data);forged.finance.creditEdits[0].reason='Outro motivo';
assert.equal(F.validateFinanceChange(data,forged),false,'Audit history cannot be rewritten');
const unaudited=structuredClone(data);unaudited.finance.creditPurchases[0].installments[1].amount=80;unaudited.finance.creditPurchases[0].amount=280;F.syncMonth(unaudited,'2099-02');
assert.equal(F.validateFinanceChange(data,unaudited),false,'Direct installment rewrites are rejected');
const twice=structuredClone(data),second=structuredClone(data.finance.creditPurchases[0].installments);second[2].amount=95;
F.editCreditInstallments(twice,purchase.id,{installments:second,reason:'Novo desconto'});
assert.equal(F.validateFinanceChange(data,twice),true);
assert.equal(twice.finance.creditEdits.length,2);
const closed=structuredClone(data);F.cancelBill(closed,'recurring:card:nubank:2099-04');
assert.throws(()=>F.editCreditInstallments(closed,purchase.id,{installments:second,reason:'Teste'}));
const past={transactions:[]};F.recordCreditPurchase(past,{cardId:'mercado_pago',description:'Antiga',category:'Outros',purchaseDate:'2020-01-01',amount:10,items:[],installments:[{date:'2020-01-01',amount:10,installmentNumber:1,installmentCount:1}]});
assert.throws(()=>F.editCreditInstallments(past,past.finance.creditPurchases[0].id,{installments:[{date:'2099-01-01',amount:10,installmentNumber:1,installmentCount:1}],reason:'Não alterar passado'}));
console.log('OK: future credit edits, exact totals, invoice refresh, audit, paid/past protection and atomic rejection.');
