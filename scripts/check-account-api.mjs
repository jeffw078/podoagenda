  globalThis.FinanceCore.setMonthPlan(adminFinance,'2026-10',{expectedIncome:3000,reserveMode:'percentage',reserveValue:10,reserveDueDay:25});
  const editedServices=corrected.services.map(s=>s.id==='service-test'?{...s,price:145}:s);
