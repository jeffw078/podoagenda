  assert.equal(adminFinanceSaved.body.data.finance.adjustments[0].reason,'Correção do saldo informado');
  assert.equal((await request({action:'adminSaveSettings',targetProfile:'podo',revision:correctionSaved.body.revision,finance:adminFinance.finance},jefferson.cookie)).status,409);
  assert.deepEqual((await request({action:'me'},jefferson.cookie)).body,personalBefore);
  console.log('OK PostgreSQL: username login, admin permissions, target isolation, original records and optimistic revisions.');
  console.log('OK PostgreSQL: validation, immutable opening balance and audit history, required correction reason, admin financial settings and referenced services.');
  console.log('OK PostgreSQL: migração preserva dados; criação, login, isolamento, troca da senha, revogação de sessões e gravação.');
