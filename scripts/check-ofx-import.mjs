import assert from 'node:assert/strict';
import {parseNubankOfx,prepareNubankOfxReplacement} from '../lib/nubank-ofx-import.js';
import {expenseHistoryUnchanged} from '../lib/expense-removals.js';
import '../src/shared/finance-core.js';
const F=globalThis.FinanceCore;
const row=(type,date,amount,id,memo)=>`<STMTTRN><TRNTYPE>${type}</TRNTYPE><DTPOSTED>${date}000000[-3:BRT]</DTPOSTED><TRNAMT>${amount}</TRNAMT><FITID>${id}</FITID><MEMO>${memo}</MEMO></STMTTRN>`;
const ofx=`OFXHEADER:100\n<OFX><CREDITCARDMSGSRSV1><CCSTMTRS><CURDEF>BRL</CURDEF><CCACCTFROM><ACCTID>test-card</ACCTID></CCACCTFROM><BANKTRANLIST><DTSTART>20260930000000</DTSTART><DTEND>20261031000000</DTEND>${row('DEBIT','20261010','-10.00','shared','Openai assinatura')}${row('DEBIT','20261010','-0.35','shared','IOF de assinatura')}${row('DEBIT','20260930','-5.00','installment','Disk Pecas - Parcela 8/10')}${row('CREDIT','20261005','100.00','payment','Pagamento recebido')}</BANKTRANLIST><LEDGERBAL><BALAMT>-15.37</BALAMT></LEDGERBAL></CCSTMTRS></CREDITCARDMSGSRSV1></OFX>`;
const input={username:'jefferson',ofx,expenseMonth:'2026-10',invoiceDueDate:'2026-11-07',asOf:'2026-11-02',createdAt:'2026-11-02T16:00:00.000Z'};
const parsed=parseNubankOfx(ofx);
assert.equal(parsed.charges.length,3,'Shared FITID for IOF and its purchase must preserve both charges');
assert.equal(new Set(parsed.charges.map(r=>r.id)).size,3);
assert.equal(parsed.chargeTotal,15.35);
assert.equal(parsed.invoiceTotal,15.37);
assert.equal(parsed.ignoredPayments,1);
assert.equal(parsed.charges[2].purchaseDate,'2026-09-30');
assert.deepEqual(parseNubankOfx(ofx.replace(/<\/TRNTYPE>|<\/DTPOSTED>|<\/TRNAMT>|<\/FITID>|<\/MEMO>|<\/CURDEF>|<\/ACCTID>/g,'\n')).charges,parsed.charges,'Unclosed OFX SGML leaf tags are supported');
assert.throws(()=>parseNubankOfx(ofx.replace('-10.00','-10x00')));
assert.throws(()=>parseNubankOfx(ofx.replace('20261010','20260230')));
assert.throws(()=>parseNubankOfx(ofx.replace('Pagamento recebido','Estorno de compra')),/cr[eé]dito|estorno/i);
assert.throws(()=>parseNubankOfx(ofx.replace('-15.37','-10.00')),/total|concilia/i);
assert.throws(()=>parseNubankOfx(ofx.replace('</BANKTRANLIST>',row('DEBIT','20261010','-10.00','shared','Openai assinatura')+'</BANKTRANLIST>')),/duplic/i);
