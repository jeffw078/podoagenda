import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const html=await readFile(new URL('../index.html',import.meta.url),'utf8');
const services=[{id:'used',name:'Serviço com histórico',duration:60,price:100},{id:'free',name:'Serviço sem uso',duration:30,price:50}];
const db={services,appointments:[{id:'past',serviceIds:['used'],date:'2020-01-01',status:'concluido'}]};
const before=structuredClone(db.appointments),nodes=new Map();let saves=0,confirm=true;
const context=vm.createContext({db,$:id=>{if(!nodes.has(id))nodes.set(id,{innerHTML:''});return nodes.get(id)},confirm:()=>confirm,persist(){saves++},closeModal(){},renderAll(){},esc:String,durationLabel:String,money:String});
vm.runInContext(html.match(/^function deleteService.*$/m)[0]+'\n'+html.match(/^function renderServices.*$/m)[0],context);
confirm=false;context.deleteService('used');assert.equal(saves,0);
confirm=true;context.deleteService('used');assert.equal(db.services.find(s=>s.id==='used').archived,true);
assert.deepEqual(db.appointments,before,'Deleting a catalog service preserves appointments');
context.renderServices();assert.doesNotMatch(nodes.get('servicesList').innerHTML,/Serviço com histórico/);
assert.match(nodes.get('servicesList').innerHTML,/Excluir/);
context.deleteService('free');assert.equal(db.services.some(s=>s.id==='free'),false);
context.renderServices();assert.match(nodes.get('servicesList').innerHTML,/primeiro serviço/);
assert.equal(saves,2);
assert.match(html,/db\.services\.filter\(s=>!s\.archived\|\|chosen\.includes\(s\.id\)\)/,'Archived services are offered only to existing bookings already using them');
console.log('OK: service deletion, cancellation, historical preservation and removal from active catalog.');
